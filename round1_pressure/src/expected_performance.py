class ExpectedPerformanceEngine:
    """
    Computes statistically defensible ordinary performance baselines,
    evaluates player pressure-versus-ordinary differentials, and models
    hierarchical Bayesian shrinkage without creating player rankings.
    """

    IPL_COMP_IDS = {1358, 1715, 2193, 2725, 3298}
    QUALIFIED_BALLS_MIN = 30

