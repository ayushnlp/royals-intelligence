    def compute_qualification_sensitivity(self, thresholds: Optional[List[int]] = None) -> pd.DataFrame:
        """
        Evaluates model sensitivity across multiple qualification thresholds.
        Tests thresholds: 10, 20, 30, 50, 75, 100 legal pressure balls.
        Reports qualified/excluded counts, EB hyperparameters, reliability, and competition coverage.
        """
        if thresholds is None:
            thresholds = [10, 20, 30, 50, 75, 100]

        records = []

        # Batting Sensitivity
        b_df = self.bat_differentials_strict.copy()
        pres_bat = self.bat_events_strict[
            self.bat_events_strict["is_primary_scope"]
            & self.bat_events_strict["outcome_is_legal"]
            & self.bat_events_strict["is_pressure_event"]
        ]
        tier_bat = pres_bat.groupby("player_id")["comp_tier"].agg(
            ipl_balls=lambda s: int((s == "IPL").sum()),
            t20i_balls=lambda s: int((s == "Senior T20I").sum()),
        ).reset_index()
        b_df = b_df.merge(tier_bat, on="player_id", how="left").fillna({"ipl_balls": 0, "t20i_balls": 0})

        for th in thresholds:
            q_mask = b_df["pressure_legal_balls"] >= th
            n_qual = int(q_mask.sum())
            n_excl = int(len(b_df) - n_qual)

            diff_q = b_df.loc[q_mask, "diff_strike_rate"]
            se_q = b_df.loc[q_mask, "se_strike_rate"]

            if n_qual >= 5:
                w_q = 1.0 / (se_q ** 2)
                mu = float(np.sum(w_q * diff_q) / np.sum(w_q))
                q_stat = float(np.sum(w_q * (diff_q - mu) ** 2))
                df = n_qual - 1
                c_denom = float(np.sum(w_q) - np.sum(w_q ** 2) / np.sum(w_q))
                tau2 = max(0.0, (q_stat - df) / c_denom)
                tau = float(np.sqrt(tau2))
                b_fact = (se_q ** 2) / (se_q ** 2 + tau2)
                rel = 1.0 - b_fact
                post_se = np.sqrt((se_q ** 2 * tau2) / (se_q ** 2 + tau2))
                med_rel = float(rel.median())
                med_post_se = float(post_se.median())
            else:
                mu, tau, med_rel, med_post_se = 0.0, 1.0, 0.0, 1.0

            qual_df = b_df[q_mask]
            has_ipl = int((qual_df["ipl_balls"] > 0).sum())
            has_t20i = int((qual_df["t20i_balls"] > 0).sum())
            both = int(((qual_df["ipl_balls"] > 0) & (qual_df["t20i_balls"] > 0)).sum())

            records.append({
                "discipline": "BATTING",
                "metric": "Strike Rate Differential",
                "threshold_balls": th,
                "qualified_players": n_qual,
                "excluded_players": n_excl,
                "prior_mean_mu": mu,
                "prior_std_tau": tau,
                "median_reliability": med_rel,
                "median_posterior_se": med_post_se,
                "ipl_covered_players": has_ipl,
                "t20i_covered_players": has_t20i,
                "both_covered_players": both,
            })

        # Bowling Sensitivity
        bw_df = self.bowl_differentials_strict.copy()
        pres_bowl = self.bowl_events_strict[
            self.bowl_events_strict["is_primary_scope"]
            & self.bowl_events_strict["outcome_is_legal"]
            & self.bowl_events_strict["is_pressure_event"]
        ]
        tier_bowl = pres_bowl.groupby("player_id")["comp_tier"].agg(
            ipl_balls=lambda s: int((s == "IPL").sum()),
            t20i_balls=lambda s: int((s == "Senior T20I").sum()),
        ).reset_index()
        bw_df = bw_df.merge(tier_bowl, on="player_id", how="left").fillna({"ipl_balls": 0, "t20i_balls": 0})

        for th in thresholds:
            q_mask = bw_df["pressure_legal_balls"] >= th
            n_qual = int(q_mask.sum())
            n_excl = int(len(bw_df) - n_qual)

            diff_q = bw_df.loc[q_mask, "diff_economy"]
            se_q = bw_df.loc[q_mask, "se_economy"]

            if n_qual >= 5:
                w_q = 1.0 / (se_q ** 2)
                mu = float(np.sum(w_q * diff_q) / np.sum(w_q))
                q_stat = float(np.sum(w_q * (diff_q - mu) ** 2))
                df = n_qual - 1
                c_denom = float(np.sum(w_q) - np.sum(w_q ** 2) / np.sum(w_q))
                tau2 = max(0.0, (q_stat - df) / c_denom)
                tau = float(np.sqrt(tau2))
                b_fact = (se_q ** 2) / (se_q ** 2 + tau2)
                rel = 1.0 - b_fact
                post_se = np.sqrt((se_q ** 2 * tau2) / (se_q ** 2 + tau2))
                med_rel = float(rel.median())
                med_post_se = float(post_se.median())
            else:
                mu, tau, med_rel, med_post_se = 0.0, 1.0, 0.0, 1.0

            qual_df = bw_df[q_mask]
            has_ipl = int((qual_df["ipl_balls"] > 0).sum())
            has_t20i = int((qual_df["t20i_balls"] > 0).sum())
            both = int(((qual_df["ipl_balls"] > 0) & (qual_df["t20i_balls"] > 0)).sum())

            records.append({
                "discipline": "BOWLING",
                "metric": "Economy Differential",
                "threshold_balls": th,
                "qualified_players": n_qual,
                "excluded_players": n_excl,
                "prior_mean_mu": mu,
                "prior_std_tau": tau,
                "median_reliability": med_rel,
                "median_posterior_se": med_post_se,
                "ipl_covered_players": has_ipl,
                "t20i_covered_players": has_t20i,
                "both_covered_players": both,
            })

        self.qualification_sensitivity_df = pd.DataFrame(records)
        return self.qualification_sensitivity_df

