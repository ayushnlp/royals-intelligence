        self.bowl_events_perm: Optional[pd.DataFrame] = None

        # Baselines
        self.bat_baseline_df: Optional[pd.DataFrame] = None
        self.bowl_baseline_df: Optional[pd.DataFrame] = None

        # Differentials
        self.bat_differentials_strict: Optional[pd.DataFrame] = None
